import { expect, test } from '@playwright/test'

test('a learner can complete a lesson and keep progress after reload', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('link', { name: 'Begin course' }).click()
  await expect(page.getByRole('heading', { name: 'Begin where you are' })).toBeVisible()
  await expect(page.getByText('Original passage')).toBeVisible()
  await page.getByRole('button', { name: 'Mark complete' }).click()
  await expect(page.getByRole('button', { name: 'Completed' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Completed' })).toBeVisible()
})

