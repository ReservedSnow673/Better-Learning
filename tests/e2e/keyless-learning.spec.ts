test('encrypted credentials can be unlocked after reload', async ({ page }) => {
  await page.goto('/settings')
  await page.getByRole('button', { name: 'OpenAI' }).click()
  await page.getByLabel('API key', { exact: true }).fill('temporary-test-key')
  await page.getByRole('checkbox', { name: 'Remember encrypted keys' }).check()
  await page.getByLabel('Passphrase').fill('test passphrase')
  await page.getByRole('button', { name: 'Save encrypted' }).click()
  await expect(page.getByText('Encrypted credentials saved in this browser.')).toBeVisible()
  await page.reload()
  await page.getByLabel('Passphrase').fill('test passphrase')
  await page.getByRole('button', { name: 'Unlock' }).click()
  await expect(page.getByText('Credentials unlocked for this session.')).toBeVisible()
  await expect(page.getByLabel('API key', { exact: true })).toHaveValue('temporary-test-key')
})

test('keyboard users can skip navigation and open the primary source', async ({ page, context }) => {
  await page.goto('/')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('link', { name: 'Skip to content' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.locator('#main-content')).toBeFocused()

  await page.goto('/course/marcus-aurelius-meditations/lesson/lesson-1')
  await page.getByRole('link', { name: 'View source evidence' }).click()
  if ((page.viewportSize()?.width ?? 1200) <= 1030) await expect(page.getByRole('tab', { name: 'Sources' })).toHaveAttribute('aria-selected', 'true')
  const sourceLink = page.getByRole('link', { name: 'Open bundled text' })
  const [sourcePage] = await Promise.all([context.waitForEvent('page'), sourceLink.click()])
  await sourcePage.waitForLoadState('domcontentloaded')
  expect(sourcePage.url()).toContain('/sources/meditations.txt')
  await sourcePage.close()
})

